// 與既有資料保持相同格式：double-stringify
// 既有資料是字串形式存在 PG json 欄位（`"{...}"`），前端 JSON.parse(content) 依此預期
// 寫入時先手動 JSON.stringify 一次，Sequelize 會再自動 stringify 一次 → double-wrap
(async () => {
    for (const [idStr, content] of Object.entries(DATA)) {
        const id = parseInt(idStr, 10);
        const contentString = JSON.stringify(content);
        await Submit.update({ content: contentString }, { where: { id } });
        console.log(`updated submit id=${id}`);
    }
    console.log('done');
    process.exit(0);
})().catch(err => {
    console.error(err);
    process.exit(1);
});
